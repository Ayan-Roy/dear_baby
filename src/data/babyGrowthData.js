export function getBabyGrowth(week) {
  const targetWeek = Math.max(1, Math.min(40, Number(week) || 24));
  const availableWeeks = Object.keys(BABY_GROWTH_DATA).map(Number).sort((a, b) => a - b);
  
  let closest = availableWeeks[0];
  for (let w of availableWeeks) {
    if (w <= targetWeek) closest = w;
  }
  
  return BABY_GROWTH_DATA[closest] || BABY_GROWTH_DATA[24];
}
